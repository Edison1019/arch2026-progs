/* Host-only generator. Original move coordinates and transition tables come
 * from Edison1019/minirubik, commit 4b2952495e2e21109533c27dc4200985b94ab5b7.
 * The target never builds or stores the complete BFS distance array.
 */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include "../src/rubik/pdb_tables.h"
#define N (5040u * 729u)
static uint8_t distance[N], back[N];
static uint32_t queue[N], near[13000], far[3000], bloom[2048];
static int compare(const void *a, const void *b)
{
    uint32_t x = *(const uint32_t *) a, y = *(const uint32_t *) b;
    return (x > y) - (x < y);
}
static void emit(FILE *c,
                 FILE *s,
                 const char *cn,
                 const char *sn,
                 const uint32_t *data,
                 unsigned n)
{
    fprintf(c, "static const uint32_t %s[%u] = {\n", cn, n);
    fprintf(s, "    .balign 4\n%s:\n", sn);
    for (unsigned i = 0; i < n; i++) {
        fprintf(c, "%uu,%s", data[i], (i % 8 == 7) ? "\n" : " ");
        fprintf(s, "    .word %u\n", data[i]);
    }
    fprintf(c, "\n};\n");
}
int main(void)
{
    for (unsigned i = 0; i < N; i++)
        distance[i] = 255;
    unsigned head = 0, tail = 1;
    distance[0] = 0;
    back[0] = 15;
    while (head < tail) {
        uint32_t k = queue[head++], p = k / 729, o = k % 729;
        for (unsigned face = 0; face < 3; face++) {
            unsigned np = p, no = o;
            for (unsigned turn = 0; turn < 3; turn++) {
                np = perm_trans[np][face];
                no = ori_trans[no][face];
                uint32_t next = np * 729 + no;
                if (distance[next] == 255) {
                    distance[next] = distance[k] + 1;
                    back[next] = (uint8_t) (3 * face + 2 - turn);
                    queue[tail++] = next;
                }
            }
        }
    }
    unsigned nn = 0, nf = 0, max = 0;
    for (unsigned k = 0; k < N; k++) {
        uint32_t key = ((k / 729) << 10) | (k % 729);
        unsigned d = distance[k];
        if (d > max)
            max = d;
        if (d <= 5) {
            if (nn >= 13000)
                return 2;
            near[nn++] = (key << 7) | (d << 4) | back[k];
            unsigned h = (key ^ (key >> 10) ^ (key >> 16)) & 65535;
            bloom[h >> 5] |= 1u << (h & 31);
        }
        if (d == 11) {
            if (nf >= 3000)
                return 2;
            far[nf++] = key;
        }
    }
    if (tail != N || max != 11 || nn != 12224 || nf != 2644)
        return 3;
    qsort(near, nn, sizeof(uint32_t), compare);
    qsort(far, nf, sizeof(uint32_t), compare);
    FILE *c = fopen("src/rubik/search_tables.h", "w");
    FILE *s = fopen("src/rubik/tables.inc", "w");
    if (!c || !s)
        return 4;
    fprintf(c,
            "/* Generated by mytests/rubik_generate.c. */\n#pragma "
            "once\n#include <stdint.h>\n");
    fprintf(s,
            "# Generated by mytests/rubik_generate.c.\n    .section .rodata\n  "
            "  .balign 4\n.Lr_perm:\n");
    for (unsigned i = 0; i < 5040; i++)
        fprintf(s, "    .half %u, %u, %u\n", perm_trans[i][0], perm_trans[i][1],
                perm_trans[i][2]);
    fprintf(s, ".Lr_ori:\n");
    for (unsigned i = 0; i < 729; i++)
        fprintf(s, "    .half %u, %u, %u\n", ori_trans[i][0], ori_trans[i][1],
                ori_trans[i][2]);
    fprintf(s, ".Lr_hp:\n");
    for (unsigned i = 0; i < 5040; i++)
        fprintf(s, "    .byte %u\n", pdb_permutation[i]);
    fprintf(s, ".Lr_ho:\n");
    for (unsigned i = 0; i < 729; i++)
        fprintf(s, "    .byte %u\n", pdb_orientation[i]);
    emit(c, s, "rubik_near", ".Lr_near", near, nn);
    emit(c, s, "rubik_diameter", ".Lr_diameter", far, nf);
    emit(c, s, "rubik_bloom", ".Lr_bloom", bloom, 2048);

    FILE *cases = fopen("mytests/rubik_cases.h", "w");
    if (!cases)
        return 5;
    fprintf(
        cases,
        "/* Generated by mytests/rubik_generate.c; host BFS distances. */\n");
    fprintf(cases,
            "static const struct profile_case { const char *state; int "
            "distance; } profile_cases[] = {\n");
    unsigned ten = 0, count = 0;
    for (unsigned k = 0; k < N; k++) {
        unsigned d = distance[k];
        int selected = (d == 11);
        if (d == 10 && ((ten++ & 255) == 0))
            selected = 1;
        if (k % 4093 == 0)
            selected = 1;
        if (!selected)
            continue;
        unsigned pr = k / 729, orr = k % 729,
                 available[7] = {0, 1, 2, 3, 4, 5, 6};
        const unsigned factorial[7] = {720, 120, 24, 6, 2, 1, 1};
        char state[15];
        for (unsigned i = 0; i < 7; i++) {
            unsigned q = pr / factorial[i];
            pr %= factorial[i];
            state[i] = (char) ('1' + available[q]);
            for (unsigned j = q; j < 6 - i; j++)
                available[j] = available[j + 1];
        }
        unsigned sum = 0;
        for (unsigned i = 6; i-- > 0;) {
            unsigned digit = orr % 3;
            orr /= 3;
            state[7 + i] = (char) ('1' + digit);
            sum += digit;
        }
        state[13] = (char) ('1' + (3 - sum % 3) % 3);
        state[14] = 0;
        fprintf(cases, "{\"%s\", %u},\n", state, d);
        count++;
    }
    fprintf(cases, "};\n");
    if (fclose(cases))
        return 6;
    printf("profile cases=%u\n", count);
    int failed = ferror(c) || ferror(s);
    if (fclose(c) || fclose(s))
        failed = 1;
    printf("states=%u maximum=%u near=%u diameter=%u\n", tail, max, nn, nf);
    return failed;
}
