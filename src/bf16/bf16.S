    .text
    .align 2
    .globl bf16_from_f32_asm
    .type bf16_from_f32_asm, @function
bf16_from_f32_asm:
    # a0: input/result; t0: retained half; t1/t2: exponent and rounding.
    srli t0, a0, 16
    li t2, 0x7f800000
    and t1, a0, t2
    beq t1, t2, .Lf32_special
    # The discarded half below 0x8000 cannot round upward. Otherwise its
    # lower 15 bits distinguish above-half from a tie, which uses t0's LSB.
    slli t1, a0, 16
    bgez t1, .Lf32_special
    slli t1, t1, 1
    bnez t1, .Lf32_up
    andi t1, t0, 1
    add t0, t0, t1
.Lf32_special:
    mv a0, t0
    ret
.Lf32_up:
    addi a0, t0, 1
    ret
    .size bf16_from_f32_asm, .-bf16_from_f32_asm

    .globl bf16_mul_asm
    .type bf16_mul_asm, @function
    .align 2
bf16_mul_asm:
    # a0/a1: original operands, then scratch/result. a2: result sign.
    # a3/a4: exponents; a5/a6: mantissas; a7: product; t0..t2: scratch.
    xor a2, a0, a1
    li t0, 0x8000
    and a2, a2, t0
    srli a3, a0, 7
    andi a3, a3, 255
    srli a4, a1, 7
    andi a4, a4, 255
    andi a5, a0, 127
    andi a6, a1, 127
    li t0, 255
    beq a3, t0, .Lmul_special_a
    beq a4, t0, .Lmul_special_b
    li t0, 0x7fff
    and t1, a0, t0
    and t2, a1, t0
    beqz t1, .Lmul_zero
    beqz t2, .Lmul_zero
    beqz a3, .Lmul_denorm_a
    ori a5, a5, 128
.Lmul_norm_b:
    beqz a4, .Lmul_denorm_b
    ori a6, a6, 128
.Lmul_product:
    # Eight-bit shift-and-add. The leading bit of a6 is always set.
    li a7, 0
.Lmul_loop:
    andi t0, a6, 1
    beqz t0, .Lmul_next
    add a7, a7, a5
.Lmul_next:
    slli a5, a5, 1
    srli a6, a6, 1
    bnez a6, .Lmul_loop
    add a3, a3, a4
    addi a3, a3, -127
    srli t0, a7, 15
    beqz t0, .Lmul_scaled
    srli a7, a7, 1
    addi a3, a3, 1
.Lmul_scaled:
    srli a7, a7, 7
    li t0, 255
    bge a3, t0, .Lmul_inf
    blez a3, .Lmul_underflow
    slli a3, a3, 7
    andi a7, a7, 127
    or a0, a3, a7
    or a0, a0, a2
    ret
.Lmul_denorm_a:
    li a3, 1
.Lmul_shift_a:
    slli a5, a5, 1
    addi a3, a3, -1
    sltiu t0, a5, 128
    bnez t0, .Lmul_shift_a
    j .Lmul_norm_b
.Lmul_denorm_b:
    li a4, 1
.Lmul_shift_b:
    slli a6, a6, 1
    addi a4, a4, -1
    sltiu t0, a6, 128
    bnez t0, .Lmul_shift_b
    j .Lmul_product
.Lmul_underflow:
    li t0, -6
    blt a3, t0, .Lmul_zero
    li t0, 1
    sub t0, t0, a3
    andi a7, a7, 127
    srl a7, a7, t0
    or a0, a7, a2
    ret
.Lmul_special_a:
    bnez a5, .Lmul_return
    li t0, 0x7fff
    and t0, a1, t0
    beqz t0, .Lmul_nan
    j .Lmul_inf
.Lmul_special_b:
    beqz a6, .Lmul_b_inf
    mv a0, a1
    ret
.Lmul_b_inf:
    li t0, 0x7fff
    and t0, a0, t0
    beqz t0, .Lmul_nan
.Lmul_inf:
    li a0, 0x7f80
    or a0, a0, a2
.Lmul_return:
    ret
.Lmul_nan:
    li a0, 0x7fc0
    ret
.Lmul_zero:
    mv a0, a2
    ret
    .size bf16_mul_asm, .-bf16_mul_asm

